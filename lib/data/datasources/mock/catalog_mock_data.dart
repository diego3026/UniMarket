  static ProductModel _p(
    String id,
    String name,
    String description,
    double price,
    double? discount,
    String category,
    String storeId, {
    double rating = 4.5,
    bool featured = false,
  }) {
    final store = storeById(storeId);
    return ProductModel(
      id: id,
      name: name,
      description: description,
      price: price,
      discountPrice: null, // los descuentos vienen de PromotionsCubit
      category: category,
      imageUrl: '',
      stock: 20,
      rating: rating,
      isFeatured: featured,
      createdAt: '2026-0${(int.parse(id) % 9) + 1}-01T10:00:00Z',
      storeId: storeId,
      storeName: store?.name ?? '',
    );
  }
